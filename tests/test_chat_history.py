"""Chat: a message center for saved whispers (and opt-in guild/officer chat), kept across reloads on this PC."""
from simcore import *

A = Client('Chris Baker'); clients[A.name] = A
tick(30)
A.ex('''function __labels() local t={} for _,b in ipairs(__ns.UI.details.pools.btn) do if b:IsShown() then t[#t+1]=b.text:GetText() end end return table.concat(t,"|") end
function __texts() local t={} for _,f in ipairs(__ns.UI.details.pools.text or {}) do if f:IsShown() then t[#t+1]=f:GetText() end end return table.concat(t,"\\n") end
function __rows() local t={} for _,r in ipairs(__ns.UI.rows) do if r:IsShown() and r.data then t[#t+1]=(r.data.key or "").." | "..(r.data.title or "").." | "..(r.data.sub or "") end end return table.concat(t,"\\n") end
function __click(label) for _,b in ipairs(__ns.UI.details.pools.btn) do if b:IsShown() and b.text:GetText()==label then b:GetScript("OnClick")(b); return true end end error("Missing "..label) end''')
A.ex('__fire("CHAT_MSG_WHISPER","need a tank for DM?","Tyler Baker-Forever")')
A.ex('__fire("CHAT_MSG_WHISPER_INFORM","sure, 10 min","Tyler Baker-Forever")')
A.ex('__fire("CHAT_MSG_WHISPER","linen?","Pip Baker")')
A.ex('__fire("CHAT_MSG_GUILD","anyone selling linen?","Pip Baker")')
check('whispers are kept by default', A.ev('#__ns.ChatLog("whisper")') == 3)
check('guild chat is off until you turn it on', A.ev('#__ns.ChatLog("guild")') == 0)
A.ex('__ns.SetChatKeep("guild", true); __fire("CHAT_MSG_GUILD","anyone selling linen?","Pip Baker")')
check('guild chat is kept once turned on', A.ev('#__ns.ChatLog("guild")') == 1)
A.ex('__ns.IsTrusted=function() return false end; __ns.SetChatKeep("officer", true); __fire("CHAT_MSG_OFFICER","promo list","Pip Baker")')
check('officer chat is never kept for non-officers', A.ev('#__ns.ChatLog("officer")') == 0)
A.ex('__ns.IsTrusted=function() return true end; __fire("CHAT_MSG_OFFICER","promo list","Pip Baker")')
check('officers can keep officer chat', A.ev('#__ns.ChatLog("officer")') == 1)
A.ex('issecretvalue=function(v) return v=="SECRET" end; __fire("CHAT_MSG_WHISPER","SECRET","Tyler Baker-Forever"); issecretvalue=nil')
check('hidden combat messages are kept as a placeholder', 'hid this message' in A.ev('__ns.ChatLog("whisper")[4].msg'))
A.ex('__log={}; __ns.chatReplayed=nil; __ns.ReplayChat()')
log = A.ev('table.concat(__log,"\\n")')
check('a reload puts recent whispers back in chat', 'need a tank for DM?' in log and 'To ' in log and 'whispers:' in log)
check('replayed names are clickable player links', '|Hplayer:Tyler Baker-Forever|h' in log)
# the message center
check('there are unread whispers', A.ev('__ns.ChatUnread()') >= 2)
A.ex('__ns.UI:Show(); __ns.UI:SetView("home"); __ns.UI.nav.chat:Click()')
rows = A.ev('__rows()')
check('Chat is its own page in the sidebar', A.ev('__ns.UI.view') == 'chat')
check('conversations list one row per person, newest first', rows.index('chat:w:Tyler Baker-Forever') < rows.index('chat:w:Pip Baker'))
check('kept guild and officer chat are pinned on top', rows.index('chat:guild') < rows.index('chat:w:Tyler Baker-Forever') and 'chat:officer' in rows)
check('opening Chat shows the latest conversation', A.ev('__ns.UI.details.kind') == 'chatwith' and A.ev('__ns.UI.details.key') == 'w:Tyler Baker-Forever')
tx = A.ev('__texts()')
check('the conversation shows both sides', 'need a tank for DM?' in tx and 'sure, 10 min' in tx and 'You' in tx)
check('newest messages are on top', tx.index('sure, 10 min') < tx.index('need a tank for DM?'))
check('the Chat page gives the conversation the wider side', A.ev('__ns.UI.details.panelWidth') > 300 or A.ev('__ns.UI.details.panelWidth') == A.ev('__ns.UI.details:GetWidth()'))
check('reading a conversation clears its unread count only', A.ev('__ns.ChatUnreadFor("w:Tyler Baker-Forever")') == 0 and A.ev('__ns.ChatUnreadFor("w:Pip Baker")') == 1)
check('guild chat has its own unread count', A.ev('__ns.ChatUnreadGuild()') >= 1)
A.ex('''for _,e in ipairs(__ns.UI.details.pools.box) do if e:IsShown() then e:SetText("on my way") end end; __log={}''')
A.ex('__click("Send")')
check('Send whispers from the panel', 'on my way' in A.ev('table.concat(__log,"\\n")'))
A.ex('__ns.UI:OpenDetails("chatwith","guild")')
A.ex('''for _,e in ipairs(__ns.UI.details.pools.box) do if e:IsShown() then e:SetText("hi all") end end; __log={}''')
A.ex('__click("Send")')
check('you can reply in guild chat too', '[GUILD] hi all' in A.ev('table.concat(__log,"\\n")'))
A.ex('__ns.UI:OpenDetails("chatnew","new")')
check('New message lists online guildmates', 'Start' in A.ev('__labels()'))
A.ex('__ns.UI:OpenDetails("chatsettings","all")')
lb = A.ev('__labels()')
check('settings keep and clear each chat', '[x] Keep whispers' in lb and '[x] Keep guild chat' in lb and 'Clear' in lb)
A.ex('__click("[x] Show the last hour after a reload"); __log={}; __ns.ReplayChat()')
check('replay can be turned off', A.ev('#__log') == 0)
# pop-out messenger
A.ex('__ns.OpenMessenger("w:Tyler Baker-Forever")')
check('Pop out opens a messenger window', A.ev('EPUGuildMessenger:IsShown()'))
mt = A.ev('EPUGuildMessenger.text:GetText()')
check('the messenger shows the newest message first', mt.index('sure, 10 min') < mt.index('need a tank for DM?'))
check('messages from the same person are grouped under one name', mt.count('Tyler Baker') <= 2)
A.ex('EPUGuildMessenger.box:SetText("brb"); __log={}; EPUGuildMessenger.box.onEnter(EPUGuildMessenger.box)')
check('you can reply from the messenger', 'brb' in A.ev('table.concat(__log,"\\n")'))
A.ex('__ns.MinimizeMessenger(true); __ns.cdb.chatSeenAt = time() - 5; __fire("CHAT_MSG_WHISPER","you there?","Tyler Baker-Forever")'); tick(1)
check('minimized, it becomes a bubble with an unread count', not A.ev('EPUGuildMessenger:IsShown()') and A.ev('EPUGuildChatBubble:IsShown()') and A.ev('EPUGuildChatBubble.badge:IsShown()') and A.ev('EPUGuildChatBubble.badge.text:GetText()') == str(A.ev('__ns.ChatUnread()')))
A.ex('EPUGuildChatBubble:GetScript("OnClick")(EPUGuildChatBubble,"LeftButton")'); tick(1)
check('the bubble has a separate guild counter', A.ev('EPUGuildChatBubble.gbadge ~= nil'))
check('clicking the bubble opens the window again', A.ev('EPUGuildMessenger:IsShown()') and not A.ev('EPUGuildChatBubble:IsShown()'))
check('restoring shows the new whisper on top', A.ev('EPUGuildMessenger.text:GetText()').find('you there?') < A.ev('EPUGuildMessenger.text:GetText()').find('sure, 10 min'))
A.ex('__ns.CloseMessenger()')
check('it remembers being closed', not A.ev('EPUGuildMessenger:IsShown()') and A.ev('__ns.cdb.chatlog and __ns.cdb.messenger.open') is False)
A.ex('SlashCmdList.EPUGUILD("chat")')
check('/epu chat opens the Chat page', A.ev('__ns.UI.view') == 'chat')
print('Chat tests:', check.failed, 'failed')
sys.exit(1 if check.failed else 0)
