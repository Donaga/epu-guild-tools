"""Actual stock history, waiting requests, quantities, sync and picker rules."""
from simcore import *
from pathlib import Path
import tempfile
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'epu-discord'))
import epu_core as core
A=Client('Chris Baker');B=Client('Tyler Baker');clients.update({A.name:A,B.name:B});tick(120)
A.ex("__bags[0]={{2589,10}}; __ns.SetBankAlt(true)")
check('stock snapshot publishes a persistent catalog',tick_until(lambda:B.ev('__ns.CanBankRequest(2589)') is True,60))
check('current stock is recorded independently of history',B.ev('__ns.BankRequestStock(2589)')==(10,0,10))
B.ex("__ns.G().needs.list[4306]=100; __ns.db.itemNames={[4306]='Silk Cloth'}; __ns.G().recipes['Tyler Baker']={t=__now,profs={Tailoring={items={2996}}}}")
check('wish lists and recipes are not stock history',not B.ev('__ns.CanBankRequest(4306)') and not B.ev('__ns.CanBankRequest(2996)'))
A.ex("EPUGuildInbox={{id='catalog-wait',kind='request',who='Tyler Baker',item=30001,qty=2,t=__now}}; __ns.ProcessInbox()")
check('Discord intake waits for missing catalog instead of losing the request',A.ev('__ns.G().requests["d-catalog-wait"]') is None and not A.ev('__ns.db.inboxDone["catalog-wait"]'))
A.ex("__ns.G().bank['Chris Baker'].seen[30001]=true; __ns.ProcessInbox(); EPUGuildInbox={}")
check('catalog recovery imports a waiting Discord request',A.ev('__ns.G().requests["d-catalog-wait"]~=nil') and A.ev('__ns.db.inboxDone["catalog-wait"]~=nil'))
check('unknown-bank item is rejected even by direct entry',B.ev("__ns.NewRequest(4306,1,'')") is None)
check('invalid request quantities rejected',B.ev("__ns.NewRequest(2589,-1,'')") is None and B.ev("__ns.NewRequest(2589,1.5,'')") is None)
B.ex("__first=__ns.NewRequest(2589,7,'first'); __now=__now+1; __second=__ns.NewRequest(2589,6,'second')")
check('current and excess quantities are allowed but not overpromised',B.ev('__first~=nil and __second~=nil') and B.ev('__ns.RequestRestock(__first)')==0 and B.ev('__ns.RequestRestock(__second)')==3)
check('open requests reduce displayed availability',B.ev('__ns.BankRequestStock(2589)')==(10,13,0))
B.ex("__ns.EditRequest(__first,{status='cancelled'})")
check('cancellation releases quantity for the next request',B.ev('__ns.RequestRestock(__second)')==0 and B.ev('__ns.BankRequestStock(2589)')==(10,6,4))
A.ex("__bags[0]={}; __ns.SnapshotBank()")
check('depletion syncs zero stock without forgetting the item',tick_until(lambda:B.ev('__ns.BankCount(2589)')==0,60) and B.ev('__ns.CanBankRequest(2589)'))
check('sold-out item accepts a waiting request',B.ev("__ns.NewRequest(2589,2,'waiting')") is not None)
check('sold-out availability explicitly mentions restock','Out of stock' in B.ev('__ns.BankRequestAvailability(2589)'))
B.ex("__ns.UI:Show(); __ns.UI:SetView('requests'); __ns.UI.itemBox:SetText('silk'); __ns.UI:SuggestItems(__ns.UI.itemBox)")
check('request picker excludes cached never-stocked items',not B.ev('__ns.UI.suggest:IsShown()'))
B.ex("__ns.UI.itemBox:SetText('linen'); __ns.UI:SuggestItems(__ns.UI.itemBox)")
check('request picker retains sold-out stock with quantity label',B.ev('__ns.UI.suggest:IsShown()') and B.ev('__ns.UI.suggest.rows[1].right:GetText()')=='Out of stock')
B.ex("__ns.UI.itemBox:SetText('item:4306'); __ns.UI.qtyBox:SetText('3'); __ns.UI.noteBox:SetText('Keep draft'); __ns.UI.action:GetScript('OnClick')()")
check('rejected never-stocked request preserves the draft',B.ev('__ns.UI.itemBox:GetText()')=='item:4306' and B.ev('__ns.UI.noteBox:GetText()')=='Keep draft')
B.ex("__ns.UI:SetView('bank')")
check('bank browser includes the sold-out historical item',B.ev("(function() for _,row in ipairs(__ns.UI.rows) do if row:IsShown() and row.data.item==2589 then return row.data.right=='Out of stock' end end return false end)()"))
A.ex('__ns.SetBankAlt(false)')
check('retirement preserves history but not stock',A.ev('__ns.CanBankRequest(2589)') and A.ev('__ns.BankCount(2589)')==0)
B.ex("__ns.Merge('Chris Baker',{bank={['Chris Baker']={v=__now+10,items={[4306]=4},money=0}}})")
check('legacy snapshots cannot erase known history',B.ev('__ns.CanBankRequest(2589)') and B.ev('__ns.CanBankRequest(4306)'))
B.ex("__ns.Merge('Chris Baker',{bank={['Chris Baker']={v=1,items={},seen={[2996]=true},money=0}}})")
check('older confirmed snapshot merges history without rolling stock back',B.ev('__ns.CanBankRequest(2996)') and B.ev('__ns.BankCount(4306)')==4)
B.ex("__ns.Merge('Pip Baker',{bank={['Chris Baker']={v=__now+11,items={},seen={[14047]=true},money=0}}})")
check('untrusted clients cannot invent bank history',not B.ev('__ns.CanBankRequest(14047)'))
B.ex("__ns.Merge('Chris Baker',{bank={['Chris Baker']={v=__now+11,items={},seen={[14047]='yes'},money=0}}})")
check('malformed history rejects the snapshot',not B.ev('__ns.CanBankRequest(14047)') and B.ev('__ns.BankCount(4306)')==4)
B.ex("__ns.G().donations.old={to='Chris Baker',item=14047,n=2,t=__now,who='Tyler Baker'}")
check('old bank donation records backfill real history',B.ev('__ns.CanBankRequest(14047)'))
B.ex("__delta=__ns.Delta(__ns.EmptyDigest())")
check('history is included in ordinary bank sync',B.ev('__delta.bank["Chris Baker"].seen[2589]') is True)

db={'itemNames':{2589:'Linen Cloth',4306:'Silk Cloth',2996:'Bolt of Linen Cloth',14047:'Runecloth'},'guilds':{'G - R':{
 'bank':{'Bank':{'v':1,'items':{2589:10},'seen':{2589:True,4306:True}},'Retired':{'items':{2996:99},'retired':True}},
 'needs':{'list':{14047:100}},'requests':{'a':{'who':'Tyler Baker','item':2589,'qty':7,'status':'approved','t':1},'b':{'who':'Pip Baker','item':2589,'qty':6,'status':'pending','t':2}}}}}
gd=core.GuildData(db)
check('Discord catalog uses bank history, not all cached names',set(gd.bank_catalog())=={2589,4306,2996})
check('retired holders contribute history but no available quantity',gd.bank_count(2996)==0)
check('Discord waiting quantities agree with addon allocation',gd.request_restock('a')==0 and gd.request_restock('b')==3)
check('Discord count includes outstanding approved and pending requests',gd.bank_request_stock(2589)==(10,13,0))
queued=[{'id':'new','kind':'request','item':4306,'qty':4,'t':3}]
check('unimported Discord requests count against availability',gd.bank_request_stock(4306,queued)==(0,4,0))
gd.g['requests']['d-new']={'item':4306,'qty':4,'status':'pending','t':3}
check('imported queued requests are not counted twice',gd.bank_request_stock(4306,queued)==(0,4,0))
state=core.State(str(Path(tempfile.mkdtemp())/'state.json'))
state.set_posted('b',12,'pending',core.request_signature(gd,'b',gd.requests['b']))
gd.g['bank']['Bank']['items'][2589]=20
check('restocking triggers a Discord message refresh without status change',any(rid=='b' for rid,r in core.diff(gd,state)['changed_requests']))
check('restocking removes waiting quantities',gd.request_restock('b')==0)
print('Bank catalog checks:',check.failed,'failed')
sys.exit(bool(check.failed))
