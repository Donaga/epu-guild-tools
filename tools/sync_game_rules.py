"""Rebuild EPUGuild/ForeverRules.lua from Efficient Games WoW: Forever game_rules.json.

Usage:
    python tools/sync_game_rules.py ../eg-link-output-wowf
"""
import glob
import json
import os
import sys


def build(root):
    builds = sorted(
        os.path.basename(os.path.dirname(p))
        for p in glob.glob(os.path.join(root, "data", "wowf", "*", "game_rules.json"))
    )
    trivial = {}
    prof_caps = {}
    for b in builds:
        p = os.path.join(root, "data", "wowf", b, "game_rules.json")
        with open(p, encoding="utf-8") as f:
            d = json.load(f)
        for lv_str, deltas in (d.get("trivialRange") or {}).items():
            try:
                lv = int(lv_str)
            except ValueError:
                continue
            for delta_str in deltas.keys():
                try:
                    delta = int(delta_str)
                except ValueError:
                    continue
                if lv not in trivial or delta > trivial[lv]:
                    trivial[lv] = delta
        for pid_str, tiers in (d.get("professionCaps") or {}).items():
            try:
                pid = int(pid_str)
            except ValueError:
                continue
            cap = prof_caps.setdefault(pid, {})
            for tier_str, vals in tiers.items():
                try:
                    tier = int(tier_str)
                except ValueError:
                    continue
                for v_str in vals.keys():
                    try:
                        cap[tier] = max(cap.get(tier, 0), int(v_str))
                    except ValueError:
                        pass

    lines = [
        "-- Generated by tools/sync_game_rules.py from Efficient Games WoW: Forever game_rules.json.",
        "-- Source: eg-link-output-wowf builds %s to %s." % (builds[0], builds[-1]) if builds else "-- Source: defaults",
        "local _, ns = ...",
        "",
        "-- Party trivial-XP threshold (WoW: Forever Nov 13 rule: 12 levels)",
        "ns.FOREVER_PARTY_TRIVIAL_GAP = 12",
        "",
        "-- Observed green/gray trivial level delta by player level",
        "ns.FOREVER_TRIVIAL_DELTA = {",
    ]
    for lv in sorted(trivial):
        lines.append("  [%d] = %d," % (lv, trivial[lv]))
    lines.append("}")
    lines.append("")
    lines.append("ns.FOREVER_PROFESSION_CAPS = {")
    for pid in sorted(prof_caps):
        tiers = ", ".join("[%d] = %d" % (t, prof_caps[pid][t]) for t in sorted(prof_caps[pid]))
        lines.append("  [%d] = { %s }," % (pid, tiers))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join("..", "eg-link-output-wowf")
    text = build(root)
    for target in (
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "EPUGuild", "ForeverRules.lua"),
        r"C:\Program Files (x86)\World of Warcraft\_forever_\Interface\AddOns\EPUGuild\ForeverRules.lua",
    ):
        if os.path.isdir(os.path.dirname(target)):
            with open(target, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("Wrote", target)
