"""Rebuild EPUGuild/GatheringSpots.lua from the Efficient Games WoW: Forever dataset.

Usage (from the repository root, with a checkout of
https://github.com/JIVESCORP/eg-link-output-wowf next to it):

    python tools/build_gathering_data.py ../eg-link-output-wowf

Reads every data/wowf/<build>/npcs.json and vendors.json and writes:

* herb and ore node positions, grouped by UI map and item, with nearby
  observations merged into one spot;
* the price of goods that at least two vendors sell in unlimited stock for
  money alone, per unit, at the undiscounted (Friendly or lower) price.

The dataset is licensed CC BY 4.0. Keep the attribution header in the output.
"""
import collections
import glob
import json
import os
import sys

HERB_NODES = {
    "Peacebloom": 2447, "Silverleaf": 765, "Stunted Silverleaf": 765, "Earthroot": 2449,
    "Mageroyal": 785, "Briarthorn": 2450, "Stranglekelp": 3820, "Bruiseweed": 2453,
    "Wild Steelbloom": 3355, "Grave Moss": 3369, "Kingsblood": 3356, "Liferoot": 3357,
    "Fadeleaf": 3818, "Goldthorn": 3821, "Khadgar's Whisker": 3358, "Wintersbite": 3819,
    "Firebloom": 4625, "Purple Lotus": 8831, "Arthas' Tears": 8836, "Sungrass": 8838,
    "Blindweed": 8839, "Ghost Mushroom": 8845, "Gromsblood": 8846, "Golden Sansam": 13464,
    "Dreamfoil": 13463, "Mountain Silversage": 13465, "Plaguebloom": 13466, "Icecap": 13467,
    "Black Lotus": 13468,
}
ORE_NODES = {
    "Copper Vein": 2770, "Poor Copper Vein": 2770, "Tin Vein": 2771, "Silver Vein": 2775,
    "Iron Deposit": 2772, "Gold Vein": 2776, "Mithril Deposit": 3858, "Truesilver Deposit": 7911,
    "Dark Iron Deposit": 11370, "Small Thorium Vein": 10620, "Rich Thorium Vein": 10620,
}
MERGE = 0.012  # fraction of the zone map; observations closer than this are one spot


def merge(points):
    spots = []
    for x, y in sorted(points):
        for spot in spots:
            if abs(spot[0] / spot[2] - x) < MERGE and abs(spot[1] / spot[2] - y) < MERGE:
                spot[0] += x; spot[1] += y; spot[2] += 1
                break
        else:
            spots.append([x, y, 1])
    return [(round(sx / n, 4), round(sy / n, 4)) for sx, sy, n in spots]


def spots(root, nodes):
    seen = collections.defaultdict(lambda: collections.defaultdict(set))
    for path in sorted(glob.glob(os.path.join(root, "data", "wowf", "*", "npcs.json"))):
        with open(path, encoding="utf-8") as handle:
            approached = json.load(handle).get("approached", {})
        for node in approached.values():
            item = nodes.get(node.get("name"))
            if not item:
                continue
            for p in node.get("positions", []):
                x, y, ui_map = p.get("mapX"), p.get("mapY"), p.get("uiMap")
                if ui_map and x is not None and y is not None and 0 <= x <= 1 and 0 <= y <= 1:
                    seen[ui_map][item].add((x, y))
    return {m: {i: merge(pts) for i, pts in items.items()} for m, items in seen.items()}


def vendor_prices(root):
    offers = collections.defaultdict(lambda: collections.defaultdict(set))
    for path in sorted(glob.glob(os.path.join(root, "data", "wowf", "*", "vendors.json"))):
        with open(path, encoding="utf-8") as handle:
            vendors = json.load(handle).get("vendors", {})
        for npc, vendor in vendors.items():
            for key, entry in (vendor.get("entries") or {}).items():
                if not key.startswith("item:") or entry.get("limited") or entry.get("stockMax") or entry.get("costItems"):
                    continue
                costs = entry.get("costs") or {}
                full = [c for standing, c in costs.items() if standing in ("3", "4", "5")]
                if not full or not entry.get("itemId") or not entry.get("stack"):
                    continue  # only a discounted price was seen
                offers[entry["itemId"]][max(full) / entry["stack"]].add(npc)
    prices = {}
    for item, by_price in offers.items():
        sellers = set().union(*by_price.values())
        if len(sellers) < 2:
            continue
        prices[item] = max(by_price, key=lambda price: (len(by_price[price]), price))
    return prices


def lua_spots(name, data):
    out = ["ns.%s = {" % name]
    for ui_map in sorted(data):
        out.append("  [%d] = {" % ui_map)
        for item in sorted(data[ui_map]):
            pts = ", ".join("{%s, %s}" % (repr(x), repr(y)) for x, y in data[ui_map][item])
            out.append("    [%d] = {%s}," % (item, pts))
        out.append("  },")
    out.append("}")
    return out


def build(root):
    builds = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(root, "data", "wowf", "*", "npcs.json")))
    herbs, ores, prices = spots(root, HERB_NODES), spots(root, ORE_NODES), vendor_prices(root)
    lines = [
        "local _, ns = ...",
        "-- Generated by tools/build_gathering_data.py. Do not edit by hand.",
        "-- Data from Efficient Games (https://efficient.games), licensed under CC BY 4.0.",
        "-- https://creativecommons.org/licenses/by/4.0/",
        "-- Source: eg-link-output-wowf, wowf builds %s to %s (npcs.json / approached, vendors.json)." % (builds[0], builds[-1]),
        "-- EPU grouped herb and ore observations by UI map and item and merged nearby ones.",
        "-- Positions are where players approached a node, so each spot is approximate.",
    ]
    lines += lua_spots("HERB_SPOTS", herbs)
    lines += lua_spots("ORE_SPOTS", ores)
    lines += [
        "-- Copper per unit for goods at least two observed vendors sell in unlimited stock,",
        "-- at the undiscounted price. Reputation discounts are not applied.",
        "ns.VENDOR_PRICES = {",
    ]
    row = []
    for item in sorted(prices):
        price = prices[item]
        row.append("[%d]=%s" % (item, repr(int(price)) if price == int(price) else repr(round(price, 2))))
        if len(row) == 8:
            lines.append("  " + ", ".join(row) + ","); row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    lines.append("}")
    return "\n".join(lines) + "\n", herbs, ores, prices


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    text, herbs, ores, prices = build(sys.argv[1])
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "EPUGuild", "GatheringSpots.lua")
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    count = lambda data: sum(len(p) for items in data.values() for p in items.values())
    print("herb spots: %d in %d maps; ore spots: %d in %d maps; vendor prices: %d" % (
        count(herbs), len(herbs), count(ores), len(ores), len(prices)))
