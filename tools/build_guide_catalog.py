"""Validate the reviewed source registry and generate offline addon data."""
from pathlib import Path
import argparse,datetime,json,re
from urllib.parse import urlparse

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'data/guide_sources.json'
TARGET=ROOT/'EPUGuild/GuideCatalog.lua'
HOSTS={'www.method.gg','mobalytics.gg','www.icy-veins.com','www.wow-professions.com','www.60.tools','www.wowhead.com','forevermastery.com'}
CLASSES={'DRUID','HUNTER','MAGE','PALADIN','PRIEST','ROGUE','SHAMAN','WARLOCK','WARRIOR'}
PROFESSIONS={129,164,165,171,182,185,186,197,202,333,356,393}
FOCUSES={'DRUID':{'Balance','Feral','Restoration'},'HUNTER':{'Beast Mastery','Marksmanship','Survival'},'MAGE':{'Arcane','Fire','Frost'},'PALADIN':{'Holy','Protection','Retribution'},'PRIEST':{'Discipline','Holy','Shadow'},'ROGUE':{'Assassination','Combat','Subtlety'},'SHAMAN':{'Elemental','Enhancement','Restoration'},'WARLOCK':{'Affliction','Demonology','Destruction'},'WARRIOR':{'Arms','Fury','Protection'}}

def validate(data):
    if data.get('edition')!='Forever' or data.get('schema')!=1:raise ValueError('Unsupported guide registry')
    ids=set()
    for r in data['guides']:
        if r['id'] in ids or not re.fullmatch('[a-z0-9-]+',r['id']):raise ValueError('Invalid/duplicate guide ID')
        ids.add(r['id'])
        u=urlparse(r['url'])
        if u.scheme!='https' or u.hostname not in HOSTS or u.username or u.password:raise ValueError('Unapproved source URL')
        if u.hostname not in {'www.60.tools','forevermastery.com'} and 'forever' not in u.path:raise ValueError('Wrong game edition')
        if r.get('class') not in CLASSES|{None} or r.get('profession') not in PROFESSIONS|{None}:raise ValueError('Unknown player filter')
        if r.get('spec') and not r.get('class'):raise ValueError('Specialization requires a class')
        if r.get('focus') and r['focus'] not in FOCUSES.get(r.get('class'),set()):raise ValueError('Invalid source focus')
        if r.get('notice') and (not isinstance(r['notice'],str) or len(r['notice'])>400):raise ValueError('Invalid source notice')
        if not isinstance(r.get('group'),str) or not r['group']:raise ValueError('Missing source group')
        if type(r.get('priority')) is not int or not 1<=r['priority']<=10:raise ValueError('Invalid source priority')
        if not r.get('class') and not r.get('profession') and not r.get('faction'):raise ValueError('Guide must have a relevance filter')
        if r.get('faction') not in {None,'Alliance','Horde'}:raise ValueError('Invalid faction')
        if r['status'] not in {'reviewed','prelaunch','beta','needs_review','unavailable'}:raise ValueError('Unknown source state')
        for key in ['reviewed','updated']:
            if r.get(key):datetime.date.fromisoformat(r[key])
        if r.get('updated') and r['updated']>r['reviewed']:raise ValueError('Review precedes source update')
        if not 1<=r.get('minLevel',1)<=r.get('maxLevel',60)<=60:raise ValueError('Invalid level range')
        if not 1<=r.get('minSkill',1)<=r.get('maxSkill',300)<=300:raise ValueError('Invalid skill range')
        if not set(r['topics'])<= {'class','leveling','talents','professions'} or not r['topics']:raise ValueError('Invalid guide topics')
        for key in ['title','publisher','author','summary']:
            if not isinstance(r[key],str) or not r[key].strip():raise ValueError('Missing source metadata: '+key)
        if len(r['summary'])>500:raise ValueError('Summaries must remain short and original')
    return data

def lua(value):
    if isinstance(value,str):return '"'+value.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n').replace('\r','')+'"'
    if isinstance(value,bool):return 'true' if value else 'false'
    if isinstance(value,(int,float)):return str(value)
    if isinstance(value,list):return '{'+','.join(lua(v) for v in value)+'}'
    if isinstance(value,dict):return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in sorted(value.items()))+'}'
    if value is None:return 'nil'
    raise ValueError('Unsupported catalog value')

def build(data):
    rows=[]
    for source in sorted(validate(data)['guides'],key=lambda r:r['id']):
        r={k:v for k,v in source.items() if k not in {'pageHash','researchNote'}}
        r['reviewEpoch']=int(datetime.datetime.fromisoformat(r['reviewed']).replace(tzinfo=datetime.timezone.utc).timestamp())
        rows.append(r)
    return '-- Generated by tools/build_guide_catalog.py; edit data/guide_sources.json.\nlocal ADDON,ns=...\nns.GUIDE_CATALOG={\n'+''.join('  '+lua(r)+',\n' for r in rows)+'}\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    result=build(json.loads(SOURCE.read_text(encoding='utf-8')))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8')!=result:raise SystemExit('Guide catalog is stale; run tools/build_guide_catalog.py')
        print('Guide registry and generated catalog match.')
    else:TARGET.write_text(result,encoding='utf-8');print('Generated',TARGET.name)
